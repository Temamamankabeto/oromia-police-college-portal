CREATE TABLE IF NOT EXISTS module_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL UNIQUE
        REFERENCES institutional_modules(id) ON DELETE RESTRICT,
    approval_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    current_revision INTEGER NOT NULL DEFAULT 1,
    approved_by BIGINT REFERENCES app_users(id),
    approved_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_approval_status CHECK (
        approval_status IN (
            'PENDING',
            'UNDER_REVIEW',
            'APPROVED',
            'REVISION_REQUESTED',
            'REJECTED'
        )
    )
);

CREATE TABLE IF NOT EXISTS module_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL
        REFERENCES institutional_modules(id) ON DELETE RESTRICT,
    activity_id BIGINT REFERENCES module_activities(id),
    parent_comment_id BIGINT REFERENCES module_comments(id),
    author_id BIGINT NOT NULL REFERENCES app_users(id),
    comment_text TEXT NOT NULL,
    resolution_status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    resolved_by BIGINT REFERENCES app_users(id),
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_comment_resolution CHECK (
        resolution_status IN (
            'OPEN',
            'IN_PROGRESS',
            'RESOLVED',
            'REOPENED'
        )
    )
);

CREATE TABLE IF NOT EXISTS module_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL
        REFERENCES institutional_modules(id) ON DELETE RESTRICT,
    decision VARCHAR(30) NOT NULL,
    decision_by BIGINT NOT NULL REFERENCES app_users(id),
    remarks TEXT,
    revision_number INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_module_decision CHECK (
        decision IN (
            'APPROVED',
            'REVISION_REQUESTED',
            'REJECTED'
        )
    )
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES app_users(id),
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100) NOT NULL,
    entity_id BIGINT,
    old_values JSONB,
    new_values JSONB,
    ip_address INET,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_module_comments_module
    ON module_comments(module_id, created_at);

CREATE INDEX IF NOT EXISTS idx_module_comments_status
    ON module_comments(resolution_status);

CREATE INDEX IF NOT EXISTS idx_module_decisions_module
    ON module_decisions(module_id, created_at);

CREATE INDEX IF NOT EXISTS idx_audit_logs_entity
    ON audit_logs(entity_type, entity_id);

CREATE INDEX IF NOT EXISTS idx_audit_logs_actor
    ON audit_logs(actor_id, created_at);
