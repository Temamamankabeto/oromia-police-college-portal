-- Migration 005: Module Revision History
-- PostgreSQL 13 compatible

CREATE TABLE IF NOT EXISTS module_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL
        REFERENCES institutional_modules(id) ON DELETE RESTRICT,
    revision_number INTEGER NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    activities_snapshot JSONB NOT NULL DEFAULT '[]'::jsonb,
    change_summary TEXT,
    edited_by BIGINT NOT NULL REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_module_revision
        UNIQUE (module_id, revision_number),

    CONSTRAINT chk_revision_positive
        CHECK (revision_number > 0),

    CONSTRAINT chk_activities_snapshot_array
        CHECK (jsonb_typeof(activities_snapshot) = 'array')
);

CREATE INDEX IF NOT EXISTS idx_module_revisions_module
    ON module_revisions(module_id, revision_number DESC);

CREATE INDEX IF NOT EXISTS idx_module_revisions_editor
    ON module_revisions(edited_by, created_at);
