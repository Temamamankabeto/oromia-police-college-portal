-- OPC Portal: Module objectives and functional requirements
-- Additive migration; preserves existing modules, activities and reviews.

CREATE TABLE IF NOT EXISTS module_objectives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL
        REFERENCES institutional_modules(id) ON DELETE RESTRICT,
    objective_code VARCHAR(40),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT chk_objective_order CHECK (display_order >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_module_objective_code
ON module_objectives(module_id, objective_code)
WHERE deleted_at IS NULL AND objective_code IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_module_objectives_module
ON module_objectives(module_id, display_order)
WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS activity_functional_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL
        REFERENCES institutional_modules(id) ON DELETE RESTRICT,
    activity_id BIGINT NOT NULL
        REFERENCES module_activities(id) ON DELETE RESTRICT,
    requirement_code VARCHAR(40) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    acceptance_criteria TEXT,
    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT chk_requirement_priority CHECK (
        priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')
    ),
    CONSTRAINT chk_requirement_status CHECK (
        status IN ('DRAFT', 'UNDER_REVIEW', 'APPROVED', 'REJECTED')
    ),
    CONSTRAINT chk_requirement_order CHECK (display_order >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_activity_requirement_code
ON activity_functional_requirements(module_id, requirement_code)
WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_functional_requirements_activity
ON activity_functional_requirements(activity_id, display_order)
WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_functional_requirements_module
ON activity_functional_requirements(module_id)
WHERE deleted_at IS NULL;

-- Ensure functional requirements belong to an activity
-- in the same institutional module.
CREATE OR REPLACE FUNCTION opc_validate_requirement_activity()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM module_activities
        WHERE id = NEW.activity_id
          AND module_id = NEW.module_id
          AND deleted_at IS NULL
    ) THEN
        RAISE EXCEPTION
            'Functional requirement activity must belong to its module'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS opc_requirement_activity_validation
ON activity_functional_requirements;

CREATE TRIGGER opc_requirement_activity_validation
BEFORE INSERT OR UPDATE
ON activity_functional_requirements
FOR EACH ROW
EXECUTE FUNCTION opc_validate_requirement_activity();


-- Prevent changing parent module or activity after creation.
CREATE OR REPLACE FUNCTION opc_guard_requirement_parent()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.module_id IS DISTINCT FROM OLD.module_id
           OR NEW.activity_id IS DISTINCT FROM OLD.activity_id THEN
            RAISE EXCEPTION
                'Functional requirement cannot change its parent'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS opc_requirement_parent_guard
ON activity_functional_requirements;

CREATE TRIGGER opc_requirement_parent_guard
BEFORE UPDATE
ON activity_functional_requirements
FOR EACH ROW
EXECUTE FUNCTION opc_guard_requirement_parent();



-- Prevent objectives from moving between institutional modules.
CREATE OR REPLACE FUNCTION opc_guard_objective_parent()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE'
       AND NEW.module_id IS DISTINCT FROM OLD.module_id THEN
        RAISE EXCEPTION
            'Objective cannot change its parent module'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS opc_objective_parent_guard
ON module_objectives;

CREATE TRIGGER opc_objective_parent_guard
BEFORE UPDATE
ON module_objectives
FOR EACH ROW
EXECUTE FUNCTION opc_guard_objective_parent();


-- Validate that both new record types belong to existing modules.
CREATE OR REPLACE FUNCTION opc_validate_child_module()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM institutional_modules
        WHERE id = NEW.module_id
          AND deleted_at IS NULL
    ) THEN
        RAISE EXCEPTION
            'Parent institutional module not found'
            USING ERRCODE = '23503';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS opc_objective_module_validation
ON module_objectives;

CREATE TRIGGER opc_objective_module_validation
BEFORE INSERT OR UPDATE
ON module_objectives
FOR EACH ROW
EXECUTE FUNCTION opc_validate_child_module();

DROP TRIGGER IF EXISTS opc_requirement_module_validation
ON activity_functional_requirements;

CREATE TRIGGER opc_requirement_module_validation
BEFORE INSERT OR UPDATE
ON activity_functional_requirements
FOR EACH ROW
EXECUTE FUNCTION opc_validate_child_module();



-- Use a dedicated guard for the new child tables.
-- Lock the parent module for every write, including INSERT.
-- Review transition code must also lock the parent module
-- to guarantee serialization with these child edits.
CREATE OR REPLACE FUNCTION opc_guard_new_requirement_edit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_module_id BIGINT;
    current_status TEXT;
BEGIN
    target_module_id := CASE
        WHEN TG_OP = 'DELETE' THEN OLD.module_id
        ELSE NEW.module_id
    END;

    PERFORM 1
    FROM institutional_modules
    WHERE id = target_module_id
      AND deleted_at IS NULL
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Parent institutional module not found'
            USING ERRCODE = '23503';
    END IF;

    SELECT approval_status
    INTO current_status
    FROM module_reviews
    WHERE module_id = target_module_id;

    IF COALESCE(current_status, 'PENDING')
       NOT IN ('PENDING', 'REVISION_REQUESTED') THEN
        RAISE EXCEPTION
            'Proposal % is locked in status %',
            target_module_id, current_status
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

-- Protect objectives using the existing proposal approval guard.
DROP TRIGGER IF EXISTS opc_objective_edit_guard
ON module_objectives;

CREATE TRIGGER opc_objective_edit_guard
BEFORE INSERT OR UPDATE OR DELETE
ON module_objectives
FOR EACH ROW
EXECUTE FUNCTION opc_guard_new_requirement_edit();


-- Protect functional requirements using the same approval guard.
DROP TRIGGER IF EXISTS opc_functional_requirement_edit_guard
ON activity_functional_requirements;

CREATE TRIGGER opc_functional_requirement_edit_guard
BEFORE INSERT OR UPDATE OR DELETE
ON activity_functional_requirements
FOR EACH ROW
EXECUTE FUNCTION opc_guard_new_requirement_edit();
