-- 3. Project-level role assignments.
CREATE TABLE project_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    role_code VARCHAR(30) NOT NULL,
    assigned_by BIGINT REFERENCES app_users(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ,
    CONSTRAINT chk_project_member_role
        CHECK (role_code IN ('DEVELOPER', 'REVIEWER', 'APPROVER', 'TESTER'))
);

CREATE UNIQUE INDEX uq_active_project_member
ON project_members(project_id, user_id, role_code)
WHERE revoked_at IS NULL;

CREATE INDEX idx_project_members_user
ON project_members(user_id, project_id)
WHERE revoked_at IS NULL;

-- 4. Requirement-level role assignments.
CREATE TABLE requirement_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_id BIGINT NOT NULL
        REFERENCES activity_functional_requirements(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    role_code VARCHAR(30) NOT NULL,
    assigned_by BIGINT REFERENCES app_users(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ,
    CONSTRAINT chk_requirement_assignment_role
        CHECK (role_code IN ('DEVELOPER', 'REVIEWER', 'APPROVER', 'TESTER'))
);

CREATE UNIQUE INDEX uq_active_requirement_assignment
ON requirement_assignments(requirement_id, user_id, role_code)
WHERE revoked_at IS NULL;

CREATE INDEX idx_requirement_assignments_user
ON requirement_assignments(user_id, requirement_id)
WHERE revoked_at IS NULL;

-- 5. Independent requirement lifecycle.
-- Existing requirement.status and module_reviews remain unchanged.
CREATE TABLE requirement_lifecycle (
    requirement_id BIGINT PRIMARY KEY
        REFERENCES activity_functional_requirements(id) ON DELETE RESTRICT,
    lifecycle_status VARCHAR(30) NOT NULL DEFAULT 'CREATED',
    updated_by BIGINT REFERENCES app_users(id) ON DELETE RESTRICT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_requirement_lifecycle_status
        CHECK (
            lifecycle_status IN (
                'CREATED',
                'ASSIGNED_FOR_REVIEW',
                'UNDER_REVIEW',
                'REVIEWED',
                'APPROVED',
                'UNDER_DEVELOPING',
                'DEVELOPED',
                'DEPLOYED',
                'TESTED'
            )
        )
);

-- Initialize lifecycle records without changing existing approval status.
INSERT INTO requirement_lifecycle (requirement_id, lifecycle_status)
SELECT
    id,
    CASE
        WHEN status = 'APPROVED' THEN 'APPROVED'
        WHEN status = 'UNDER_REVIEW' THEN 'UNDER_REVIEW'
        ELSE 'CREATED'
    END
FROM activity_functional_requirements
ON CONFLICT (requirement_id) DO NOTHING;

-- 6. Immutable lifecycle event history.
CREATE TABLE requirement_workflow_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_id BIGINT NOT NULL
        REFERENCES activity_functional_requirements(id) ON DELETE RESTRICT,
    from_status VARCHAR(30),
    to_status VARCHAR(30) NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    remarks TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_requirement_workflow_events
ON requirement_workflow_events(requirement_id, created_at, id);

-- 7. Deployment evidence.
CREATE TABLE requirement_deployments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_id BIGINT NOT NULL
        REFERENCES activity_functional_requirements(id) ON DELETE RESTRICT,
    deployment_reference VARCHAR(255) NOT NULL,
    environment VARCHAR(30) NOT NULL,
    commit_sha VARCHAR(64),
    deployed_by BIGINT REFERENCES app_users(id) ON DELETE RESTRICT,
    deployed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX idx_requirement_deployments
ON requirement_deployments(requirement_id, deployed_at DESC);

-- 8. Testing evidence.
CREATE TABLE requirement_test_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_id BIGINT NOT NULL
        REFERENCES activity_functional_requirements(id) ON DELETE RESTRICT,
    tester_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    deployment_id BIGINT REFERENCES requirement_deployments(id) ON DELETE RESTRICT,
    result VARCHAR(20) NOT NULL,
    remarks TEXT,
    tested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_requirement_test_result
        CHECK (result IN ('PASSED', 'FAILED', 'BLOCKED'))
);

CREATE INDEX idx_requirement_test_results
ON requirement_test_results(requirement_id, tested_at DESC);