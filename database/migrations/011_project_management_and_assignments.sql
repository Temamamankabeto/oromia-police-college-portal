-- Allow only the initial project association during this migration.
-- All other module edits continue through the existing approval guard.
CREATE OR REPLACE FUNCTION opc_guard_proposal_edit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_module_id BIGINT;
    current_status TEXT;
BEGIN
    IF TG_TABLE_NAME = 'institutional_modules' THEN
        target_module_id :=
            CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;

        IF TG_OP = 'UPDATE'
           AND current_setting('opc.initial_project_backfill', true) = 'enabled'
           AND OLD.project_id IS NULL
           AND NEW.project_id IS NOT NULL
           AND (to_jsonb(NEW) - 'project_id') =
               (to_jsonb(OLD) - 'project_id') THEN
            RETURN NEW;
        END IF;
    ELSE
        target_module_id :=
            CASE WHEN TG_OP = 'DELETE'
                THEN OLD.module_id ELSE NEW.module_id END;

        IF TG_OP = 'UPDATE'
           AND NEW.module_id IS DISTINCT FROM OLD.module_id THEN
            RAISE EXCEPTION 'Activity cannot change its parent proposal'
                USING ERRCODE = '23514';
        END IF;

        PERFORM 1
        FROM institutional_modules
        WHERE id = target_module_id
          AND deleted_at IS NULL
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Parent proposal not found'
                USING ERRCODE = '23503';
        END IF;
    END IF;

    SELECT approval_status
    INTO current_status
    FROM module_reviews
    WHERE module_id = target_module_id;

    IF COALESCE(current_status, 'PENDING')
       NOT IN ('PENDING', 'REVISION_REQUESTED') THEN
        RAISE EXCEPTION
            'Proposal % is locked in status %',
            target_module_id, current_status
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

-- The migration runner owns the transaction.
-- Execute the guarded backfill within one PostgreSQL statement.
DO $opc_backfill$
BEGIN
    PERFORM set_config('opc.initial_project_backfill', 'enabled', true);

    UPDATE institutional_modules
    SET project_id = (
        SELECT id FROM projects WHERE project_code = 'OPC'
    )
    WHERE project_id IS NULL;

    PERFORM set_config('opc.initial_project_backfill', 'disabled', true);
END;
$opc_backfill$;

-- Restore the original approval protection before transaction commit.
CREATE OR REPLACE FUNCTION opc_guard_proposal_edit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  target_module_id bigint;
  current_status text;
BEGIN
  IF TG_TABLE_NAME = 'institutional_modules' THEN
    target_module_id :=
      CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
  ELSE
    target_module_id :=
      CASE WHEN TG_OP = 'DELETE'
        THEN OLD.module_id ELSE NEW.module_id END;

    IF TG_OP = 'UPDATE'
       AND NEW.module_id IS DISTINCT FROM OLD.module_id THEN
      RAISE EXCEPTION 'Activity cannot change its parent proposal'
        USING ERRCODE = '23514';
    END IF;

    -- Serialize activity changes with review transitions.
    PERFORM 1
    FROM institutional_modules
    WHERE id = target_module_id
      AND deleted_at IS NULL
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Parent proposal not found'
        USING ERRCODE = '23503';
    END IF;
  END IF;

  SELECT approval_status
  INTO current_status
  FROM module_reviews
  WHERE module_id = target_module_id;

  IF COALESCE(current_status, 'PENDING')
     NOT IN ('PENDING', 'REVISION_REQUESTED') THEN
    RAISE EXCEPTION
      'Proposal % is locked in status %',
      target_module_id, current_status
      USING ERRCODE = '23514';
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;
