-- Functional Requirement Review Comments
-- Independent of the existing Module Review workflow.

CREATE TABLE requirement_review_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    requirement_id BIGINT NOT NULL
        REFERENCES activity_functional_requirements(id)
        ON DELETE RESTRICT,

    author_id BIGINT NOT NULL
        REFERENCES app_users(id)
        ON DELETE RESTRICT,

    comment_type VARCHAR(30) NOT NULL DEFAULT 'COMMENT',

    comment_text TEXT NOT NULL,

    resolution_status VARCHAR(30) NOT NULL DEFAULT 'OPEN',

    resolved_by BIGINT
        REFERENCES app_users(id)
        ON DELETE RESTRICT,

    resolved_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_requirement_comment_type
        CHECK (
            comment_type IN (
                'COMMENT',
                'FINDING',
                'RECOMMENDATION',
                'CHANGE_REQUEST'
            )
        ),

    CONSTRAINT chk_requirement_comment_resolution
        CHECK (
            resolution_status IN (
                'OPEN',
                'IN_PROGRESS',
                'RESOLVED',
                'REOPENED'
            )
        ),

    CONSTRAINT chk_requirement_comment_text
        CHECK (
            char_length(btrim(comment_text)) BETWEEN 1 AND 10000
        ),

    CONSTRAINT chk_requirement_comment_resolution_actor
        CHECK (
            (resolution_status = 'RESOLVED'
                AND resolved_by IS NOT NULL
                AND resolved_at IS NOT NULL)
            OR
            (resolution_status <> 'RESOLVED'
                AND resolved_at IS NULL)
        )
);

CREATE INDEX idx_requirement_review_comments_requirement
    ON requirement_review_comments (
        requirement_id,
        created_at,
        id
    );

CREATE INDEX idx_requirement_review_comments_author
    ON requirement_review_comments (
        author_id,
        created_at DESC
    );

CREATE INDEX idx_requirement_review_comments_open
    ON requirement_review_comments (
        requirement_id,
        resolution_status
    )
    WHERE resolution_status <> 'RESOLVED';

COMMENT ON TABLE requirement_review_comments IS
'Reviewer findings, comments, recommendations and change requests for individual functional requirements.';

COMMENT ON COLUMN requirement_review_comments.comment_type IS
'COMMENT, FINDING, RECOMMENDATION or CHANGE_REQUEST.';

COMMENT ON COLUMN requirement_review_comments.resolution_status IS
'OPEN, IN_PROGRESS, RESOLVED or REOPENED.';