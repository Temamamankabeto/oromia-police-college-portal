
CREATE UNIQUE INDEX uq_requirement_review_comment_id_requirement
    ON requirement_review_comments (id, requirement_id);
CREATE TABLE requirement_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    requirement_id BIGINT NOT NULL
        REFERENCES activity_functional_requirements(id)
        ON DELETE RESTRICT,

    comment_id BIGINT NOT NULL,

    developer_id BIGINT NOT NULL
        REFERENCES app_users(id)
        ON DELETE RESTRICT,

    proposed_title VARCHAR(255) NOT NULL,
    proposed_description TEXT NOT NULL,
    proposed_acceptance_criteria TEXT,

    correction_explanation TEXT NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',

    submitted_at TIMESTAMPTZ,

    reviewed_by BIGINT
        REFERENCES app_users(id)
        ON DELETE RESTRICT,

    reviewed_at TIMESTAMPTZ,

    review_remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_requirement_correction_comment_requirement
        FOREIGN KEY (comment_id, requirement_id)
        REFERENCES requirement_review_comments(id, requirement_id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_requirement_correction_status
        CHECK (
            status IN (
                'DRAFT',
                'SUBMITTED',
                'ACCEPTED',
                'RETURNED'
            )
        ),

    CONSTRAINT chk_requirement_correction_title
        CHECK (
            char_length(btrim(proposed_title))
            BETWEEN 1 AND 255
        ),

    CONSTRAINT chk_requirement_correction_description
        CHECK (
            char_length(btrim(proposed_description)) > 0
        ),

    CONSTRAINT chk_requirement_correction_explanation
        CHECK (
            char_length(btrim(correction_explanation))
            BETWEEN 10 AND 10000
        ),

    CONSTRAINT chk_requirement_correction_submission
        CHECK (
            (status = 'DRAFT' AND submitted_at IS NULL)
            OR
            (status <> 'DRAFT' AND submitted_at IS NOT NULL)
        ),

    CONSTRAINT chk_requirement_correction_review
        CHECK (
            (
                status IN ('DRAFT', 'SUBMITTED')
                AND reviewed_by IS NULL
                AND reviewed_at IS NULL
            )
            OR
            (
                status IN ('ACCEPTED', 'RETURNED')
                AND reviewed_by IS NOT NULL
                AND reviewed_at IS NOT NULL
                AND review_remarks IS NOT NULL
                AND char_length(btrim(review_remarks)) >= 10
            )
        )
);

CREATE INDEX idx_requirement_corrections_requirement
    ON requirement_corrections (
        requirement_id,
        created_at DESC
    );

CREATE INDEX idx_requirement_corrections_comment
    ON requirement_corrections (
        comment_id,
        created_at DESC
    );

CREATE INDEX idx_requirement_corrections_developer
    ON requirement_corrections (
        developer_id,
        status
    );

CREATE INDEX idx_requirement_corrections_pending
    ON requirement_corrections (
        requirement_id,
        status
    )
    WHERE status = 'SUBMITTED';
