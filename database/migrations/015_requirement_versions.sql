
CREATE TABLE requirement_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    requirement_id BIGINT NOT NULL
        REFERENCES activity_functional_requirements(id)
        ON DELETE RESTRICT,

    version_number INTEGER NOT NULL,

    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    acceptance_criteria TEXT,

    created_by BIGINT NOT NULL
        REFERENCES app_users(id)
        ON DELETE RESTRICT,

    consolidation_remarks TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_requirement_version_number
        UNIQUE (requirement_id, version_number),

    CONSTRAINT uq_requirement_version_id_requirement
        UNIQUE (id, requirement_id),

    CONSTRAINT chk_requirement_version_number
        CHECK (version_number >= 1),

    CONSTRAINT chk_requirement_version_title
        CHECK (
            char_length(btrim(title))
            BETWEEN 1 AND 255
        ),

    CONSTRAINT chk_requirement_version_description
        CHECK (
            char_length(btrim(description)) > 0
        ),

    CONSTRAINT chk_requirement_version_remarks
        CHECK (
            char_length(btrim(consolidation_remarks))
            BETWEEN 10 AND 5000
        )
);

CREATE INDEX idx_requirement_versions_requirement
    ON requirement_versions (
        requirement_id,
        version_number DESC
    );

ALTER TABLE requirement_corrections
    ADD CONSTRAINT uq_requirement_correction_id_requirement
    UNIQUE (id, requirement_id);

CREATE TABLE requirement_version_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    requirement_id BIGINT NOT NULL,

    version_id BIGINT NOT NULL,

    correction_id BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_version_correction_version
        FOREIGN KEY (version_id, requirement_id)
        REFERENCES requirement_versions(id, requirement_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_version_correction_requirement
        FOREIGN KEY (requirement_id)
        REFERENCES activity_functional_requirements(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_version_correction_correction
        FOREIGN KEY (correction_id, requirement_id)
        REFERENCES requirement_corrections(id, requirement_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_version_correction
        UNIQUE (version_id, correction_id),

    CONSTRAINT uq_applied_requirement_correction
        UNIQUE (correction_id)
);

CREATE INDEX idx_version_corrections_requirement
    ON requirement_version_corrections (
        requirement_id,
        version_id
    );
